// gen_ntt1024_vectors.mjs -- Falcon-1024 NTT / INTT vectors from @noble/post-quantum 0.7.1
//
//   cd jsref && npm ci && node gen_ntt1024_vectors.mjs
//
// writes ../test/ntt1024_vectors.json (hex compact words) and ../test/ntt1024_vectors.sol.
// noble does not export Falcon's integer polynomial ring; getIntPoly(10) in falcon.js is
// genCrystals({ N: 1024, Q: 12289, F: 1024^-1, ROOT_OF_UNITY: 7, isKyber: false, brvBits: 10 }),
// rebuilt here from the exported _crystals.js with exactly those options. The script checks
// before emitting anything that this ring is the one falcon1024 uses: intt(ntt(a) * ntt(b)) is
// the schoolbook product mod X^1024 + 1, and intt(ntt(a)) = a.
import { genCrystals } from '@noble/post-quantum/_crystals.js';
import { falcon1024 } from '@noble/post-quantum/falcon.js';
import { shake256 } from '@noble/hashes/sha3.js';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const Q = 12289;
const N = 1024;
const F = 12277; // 1024^-1 mod q
if ((F * N) % Q !== 1) throw new Error('F');

const { NTT } = genCrystals({ N, Q, F, ROOT_OF_UNITY: 7, newPoly: (n) => new Uint16Array(n), isKyber: false, brvBits: 10 });
const ntt = (a) => NTT.encode(Uint16Array.from(a));
const intt = (a) => NTT.decode(Uint16Array.from(a));

// the options above are those of falcon.js getIntPoly (asserted on the installed source)
const require = createRequire(import.meta.url);
const src = readFileSync(require.resolve('@noble/post-quantum/falcon.js'), 'utf8');
if (!/ROOT_OF_UNITY:\s*7,/.test(src) || !/brvBits:\s*10,/.test(src) || !/isKyber:\s*false,/.test(src))
  throw new Error('falcon.js getIntPoly options changed');
if (typeof falcon1024.sign !== 'function') throw new Error('falcon1024 missing');

let ctr = 0;
const rand = (seed) => {
  const h = shake256(new TextEncoder().encode(`ntt1024-${seed}`), { dkLen: 4 * N });
  const out = new Array(N);
  for (let i = 0, j = 0; i < N; ) {
    if (j + 2 > h.length) throw new Error('rejection overflow');
    const v = (h[j] | (h[j + 1] << 8)) & 0x3fff;
    j += 2;
    if (v < Q) out[i++] = v;
  }
  ctr++;
  return out;
};

const schoolbook = (a, b) => {
  const r = new Array(N).fill(0);
  for (let i = 0; i < N; i++)
    for (let j = 0; j < N; j++) {
      const k = i + j;
      const p = (a[i] * b[j]) % Q;
      if (k < N) r[k] = (r[k] + p) % Q;
      else r[k - N] = (r[k - N] - p + Q) % Q;
    }
  return r;
};

{
  const a = rand('check-a'), b = rand('check-b');
  const na = ntt(a), nb = ntt(b);
  const prod = intt(na.map((x, i) => (x * nb[i]) % Q));
  const ref = schoolbook(a, b);
  for (let i = 0; i < N; i++) if (prod[i] !== ref[i]) throw new Error('ring product mismatch');
  const back = intt(na);
  for (let i = 0; i < N; i++) if (back[i] !== a[i]) throw new Error('roundtrip mismatch');
}

const compact = (p) => {
  const w = [];
  for (let c = 0; c < 64; c++) {
    let x = 0n;
    for (let i = 0; i < 16; i++) x |= BigInt(p[16 * c + i]) << BigInt(16 * i);
    w.push('0x' + x.toString(16).padStart(64, '0'));
  }
  return w;
};

const inputs = [];
for (let s = 0; s < 6; s++) inputs.push({ name: `random${s}`, poly: rand(s) });
inputs.push({ name: 'saturated', poly: new Array(N).fill(Q - 1) });
inputs.push({ name: 'zero', poly: new Array(N).fill(0) });
inputs.push({ name: 'one', poly: [1, ...new Array(N - 1).fill(0)] });
inputs.push({ name: 'xn1', poly: [...new Array(N - 1).fill(0), 1] });
inputs.push({ name: 'alternate', poly: Array.from({ length: N }, (_, i) => (i & 1 ? Q - 1 : 0)) });

const vectors = inputs.map(({ name, poly }) => ({
  name,
  a: compact(poly),
  ntt: compact(ntt(poly)),
  intt: compact(intt(poly)),
}));

const pkg = JSON.parse(readFileSync(new URL('./node_modules/@noble/post-quantum/package.json', import.meta.url)));
writeFileSync(new URL('../test/ntt1024_vectors.json', import.meta.url),
  JSON.stringify({ source: `@noble/post-quantum ${pkg.version}`, q: Q, n: N, vectors }, null, 1) + '\n');

let sol = `// SPDX-License-Identifier: MIT
// GENERATED by jsref/gen_ntt1024_vectors.mjs from @noble/post-quantum ${pkg.version} -- do not edit.
// Falcon-1024 NTT / INTT vectors, compact form (64 words, coefficient 16c + i in field i of word c).
pragma solidity ^0.8.25;

library Ntt1024Vectors {
    uint256 internal constant COUNT = ${vectors.length};

    function get(uint256 k) internal pure returns (string memory name, uint256[] memory a, uint256[] memory n, uint256[] memory inv) {
        a = new uint256[](64);
        n = new uint256[](64);
        inv = new uint256[](64);
`;
vectors.forEach((v, k) => {
  sol += `        ${k === 0 ? '' : 'else '}if (k == ${k}) {\n            name = "${v.name}";\n`;
  for (const [field, arr] of [['a', v.a], ['n', v.ntt], ['inv', v.intt]])
    arr.forEach((x, i) => { sol += `            ${field}[${i}] = ${x};\n`; });
  sol += `        }\n`;
});
sol += `        else revert("vector index");\n    }\n}\n`;
writeFileSync(new URL('../test/ntt1024_vectors.sol', import.meta.url), sol);
console.log(`wrote ${vectors.length} vectors (${ctr} random draws), ring checks passed`);
